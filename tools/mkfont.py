#!/usr/bin/env python3
"""Rasterise a monospace TTF into anti-aliased ASCII glyph atlases (src/font_data.h).

usage: mkfont.py FONT.ttf OUT.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = [("small", 15), ("large", 26)]
FIRST, LAST = 32, 126


def atlas(path, px):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    adv = round(font.getlength("M"))
    h = ascent + descent
    glyphs = []
    for c in range(FIRST, LAST + 1):
        im = Image.new("L", (adv, h), 0)
        ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=255)
        glyphs.append(im.tobytes())
    return adv, h, glyphs


def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = ["/* generated by tools/mkfont.py from Noto Sans Mono (SIL OFL 1.1) */",
             "#pragma once", "#include <stdint.h>", ""]
    for name, px in SIZES:
        w, h, glyphs = atlas(src, px)
        lines.append(f"#define FONT_{name.upper()}_W {w}")
        lines.append(f"#define FONT_{name.upper()}_H {h}")
        lines.append(f"static const uint8_t font_{name}_data[{len(glyphs)}][{w * h}] = {{")
        for g in glyphs:
            lines.append("  {" + ",".join(str(b) for b in g) + "},")
        lines.append("};")
        lines.append("")
    open(out, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
